export type FeaturePlacement =
  | { kind: 'MENU'; path: readonly string[] }
  | { kind: 'SIDEBAR'; screen: 'REVIEW' | 'FORM_SETUP'; section: string };

export interface FeatureEntry {
  /** 画面とテストが機能を指す安定した名前。表示名を変えてもこれは変えない。 */
  readonly id: string;
  /** メニューと一覧に出す表示名。表示名の正本はここ。 */
  readonly title: string;
  readonly category: FeatureCategory;
  /** `src/main.ts`の`export function`名。 */
  readonly entrypoint: string;
  readonly placement: readonly FeaturePlacement[];
  readonly visibility: FeatureVisibility;
  readonly requires: readonly FeatureConditionKey[];
  /** 何をするか。専門用語を使わず1文で。 */
  readonly whatItDoes: string;
  /** 作るもの・置き換わるもの。 */
  readonly whatChanges: readonly string[];
  /** 変えないもの。利用者がいちばん不安に思うところ。 */
  readonly whatDoesNotChange: readonly string[];
  /** いつ使うか。 */
  readonly whenToUse: string;
  /** 実行前に確認ダイアログを出すか。 */
  readonly confirmBeforeRun: boolean;
  /** 元に戻せない操作か。危険色の目印に使う。 */
  readonly destructive: boolean;
}

