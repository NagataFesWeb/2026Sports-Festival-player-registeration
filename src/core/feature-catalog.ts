/** 検証専用のため、カタログの対象外にする関数名のパターン。 */
export const NON_FEATURE_ENTRYPOINT_PATTERNS: readonly RegExp[] = [/ForClasp$/];

export function isNonFeatureEntrypoint(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(NON_FEATURE_ENTRYPOINTS, name)
    || NON_FEATURE_ENTRYPOINT_PATTERNS.some((pattern) => pattern.test(name));
}

export function findFeature(id: string): FeatureEntry {
  const entry = FEATURE_CATALOG.find((candidate) => candidate.id === id);
  if (!entry) throw new Error(`機能カタログに「${id}」がありません。`);
  return entry;
}

export function findFeatureByEntrypoint(entrypoint: string): FeatureEntry | undefined {
  return FEATURE_CATALOG.find((candidate) => candidate.entrypoint === entrypoint);
}
