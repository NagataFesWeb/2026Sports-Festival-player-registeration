/**
 * この管理表でできることの一覧（機能カタログ）。
 *
 * ここが機能一覧の正本。3つの画面がこの1ファイルを読む。
 *   1. スプレッドシートのメニュー（`src/main.ts`の`onOpen`）— 表示名と、モードによる出し分け
 *   2. サイドバー（`src/Sidebar.html` / `src/SettingsSidebar.html`）— 説明枠と、押せない理由
 *   3. 機能紹介ダイアログ（`src/FeatureGuide.html`）— 全機能の一覧
 *
 * ## 追加・変更するときの約束
 *
 * `src/main.ts`へ`export function`を足したら、ここへ1件足すか、載せない理由を
 * `NON_FEATURE_ENTRYPOINTS`へ書く。どちらもしないと`tests/core/featureCatalog.test.ts`が落ちる。
 * 機能を消したときも同じで、対応する行を消さないとテストが落ちる。
 * これは説明が実装より古くなるのを防ぐための仕組みで、運用の心がけではない。
 *
 * ## `requires`の位置づけ
 *
 * `requires`は「今この機能が使えるかを画面へ出すための宣言」であって、実行を止める仕組みでは
 * ない。実際の禁止は今までどおり`core/workflow.ts`の`assertActionAllowed`、
 * `gas/settings-change-service.ts`、`gas/rule-change-service.ts`などが例外で行う。
 * 両者が食い違っていないかは、エントリを足すときに人が読み合わせる。
 */

